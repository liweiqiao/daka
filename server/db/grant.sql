-- ============================================================
-- 数据库账号授权 —— 在数据库服务器上以 root（或高权限账号）执行
--
-- ★ 真实密码不写在本文件（本文件会进 git 仓库），请用 server/.env 里
--   DB_PASSWORD 的值替换下面的 <DB_PASSWORD> 占位符。
--
-- 症状：应用报 Access denied for user 'daka'@'113.100.36.226'
-- 原因：daka 账号已存在，但它的可登录主机白名单里没有应用所在机器的 IP。
--       MySQL 的权限判断是「账号 + 来源主机」两元组，
--       光有账号没授权主机，一样连不上。
-- ============================================================

-- ------------------------------------------------------------
-- 方案 A（推荐，也最省事）：允许从任何主机登录
--   适合本机和将来的云服务器都要连的情况。
--   安全性靠「3306 不要对整个互联网开放」+ 强密码来保证，
--   建议同时在云安全组里把 3306 限制到固定 IP 段。
-- ------------------------------------------------------------
CREATE USER IF NOT EXISTS 'daka'@'%' IDENTIFIED BY '<DB_PASSWORD>';
ALTER USER 'daka'@'%' IDENTIFIED BY '<DB_PASSWORD>';
GRANT ALL PRIVILEGES ON `daka`.* TO 'daka'@'%';
FLUSH PRIVILEGES;

